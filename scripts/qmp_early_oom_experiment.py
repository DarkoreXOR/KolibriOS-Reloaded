SEED = 0x5047424D

# Bounded progressive retain ceilings (physical pages only — no VA mapping).
# Firstapp freelist starts near pages_count (~64k on -m 256); post-desktop ~48k.
# Prior step ret=50000 reached ~13k free and still succeeded — escalate further.
DEFAULT_SCHEDULE = [64000]


def write_oom_limits(max_retain: int, yield_every: int = 64) -> Path:
    """Write ``oom_limits.inc`` consumed by ``asoakdrv_oom.asm``."""
    ledger = max(max_retain + 64, max_retain)
    # Keep a small headroom above retain for the single probe page.
    path = resolve("tools/allocsoak/oom_limits.inc")
    path.write_text(
        "; Generated by scripts/qmp_early_oom_experiment.py — do not edit by hand.\n"
        f"MAX_LEDGER  = {ledger}\n"
        f"MAX_RETAIN  = {max_retain}\n"
        f"YIELD_EVERY = {yield_every}\n"
        f"SEED        = {SEED:#010x}\n",
        encoding="utf-8",
    )
    return path


def build_asoakdrv_oom() -> Path:
    cfg = load_config()
    fasm = resolve(cfg["kernel"]["fasm"])
    src = resolve("tools/allocsoak/asoakdrv_oom.asm")
    out_dir = resolve("dev_build/allocsoak")
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "ASOAKDRV"
    if out.is_file():
        out.unlink()
    run_cmd([fasm, src, out], what="FASM asoakdrv_oom")
    if not out.is_file():
        raise SystemExit(f"ERROR: asoakdrv_oom binary missing: {out}")
    log.info("asoakdrv_oom built: %s (%s bytes)", out, out.stat().st_size)
    return out


def prepare_oom_image(*, max_retain: int, delete: bool | None = None) -> dict[str, Any]:
    write_oom_limits(max_retain)
    cfg = load_config()
    image_path = prepare_image(cfg, delete=delete)
    drv = build_asoakdrv_oom()
    loader = build_allocsoak()
    img_tool = ensure_kolibri_img(cfg["image"])
    run_cmd([img_tool, "put", image_path, "ASOAKDRV", drv], what="put ASOAKDRV")
    run_cmd([img_tool, "put", image_path, "ALLOCSOK", loader], what="put ALLOCSOK")
    patch_info = patch_firstapp_in_kernel_mnt(image_path, img_tool)
    recipe = {
        "schema": 1,
        "mode": "early_oom_experiment",
        "seed": f"{SEED:#010x}",
        "seed_ascii": "PGBM",
        "max_retain": max_retain,
        "image": str(image_path).replace("\\", "/"),
        "asoakdrv": str(drv).replace("\\", "/"),
        "allocsok": str(loader).replace("\\", "/"),
        "firstapp_patch": patch_info,
        "note": (
            "AllocPage retains physical pages only (no process VA growth). "
            "At most one failed AllocPage after/at ceiling."
        ),
    }
    recipe_path = resolve("dev_build/allocsoak/early-oom-recipe.json")
    recipe_path.write_text(json.dumps(recipe, indent=2) + "\n", encoding="utf-8")
    return recipe


def _live_pf(sample: dict[str, Any]) -> int | None:
    pf = sample.get("pages_free")
    if not isinstance(pf, int):
        return None
    pc = sample.get("pages_count")
    if isinstance(pc, int) and pc > 0 and pf > pc:
        return None
    # Ignore pre-init BSS zeros / nonsense before allocator is live.
    if pf < 256:
        return None
    return pf


def run_one_ceiling(
    *,
    max_retain: int,
    port: int,
    wait_s: float,
    sample_interval: float,
    digest_bytes: int,
    artifact: Path,
    disks: list[str],
) -> dict[str, Any]:
    recipe = prepare_oom_image(max_retain=max_retain, delete=None)
    image_path = resolve(LAST_IMAGE_MARKER.read_text(encoding="utf-8").strip())
    symbols = resolve_allocator_symbols()
    cfg = load_config()
    qemu = find_qemu(cfg["qemu"]["executables"])
    out_dir = resolve("dev_build/allocsoak")
    ppm = out_dir / "early-oom.ppm"
    if ppm.is_file():
        ppm.unlink()

    result: dict[str, Any] = {
        "schema": 1,
        "experiment": "early_oom",
        "seed": f"{SEED:#010x}",
        "max_retain": max_retain,
        "recipe": recipe,
        "image": str(image_path).replace("\\", "/"),
        "symbols": {
            "pages_free": symbols["pages_free"],
            "page_start": symbols["page_start"],
            "sys_pgmap": symbols["sys_pgmap"],
        },
        "qemu": {},
        "phases": [],
        "notes": [],
        "result": {"passed": False, "classification": None},
    }

    resets = [0]
    shutdowns = [0]
    sock: socket.socket | None = None
    proc: subprocess.Popen[bytes] | None = None
    early_samples: list[dict[str, Any]] = []

    try:
        qargs = build_qemu_argv(
            cfg,
            image_path=image_path,
            disks=disks or None,
            headless=True,
        )
        for i, a in enumerate(qargs):
            if a == "-qmp" and i + 1 < len(qargs):
                qargs[i + 1] = f"tcp:127.0.0.1:{port},server,nowait"
        proc = subprocess.Popen([str(qemu), *qargs], cwd=str(ROOT))
        sock = qmp_connect("127.0.0.1", port, timeout=45.0)
        greet = qmp_recv_obj(sock)
        if "QMP" not in greet:
            raise RuntimeError(f"bad QMP greeting: {greet}")
        qmp_exec(sock, {"execute": "qmp_capabilities"})

        desk = wait_desktop(
            sock,
            ppm,
            wait_s=wait_s,
            min_non_black=100000,
            splash_max=20000,
            resets=resets,
            shutdowns=shutdowns,
            symbols=symbols,
            early_samples=early_samples,
            sample_interval=sample_interval,
            digest_bytes=digest_bytes,
        )
        result["qemu"].update(desk)

        baseline = sample_allocator(sock, symbols, digest_max_bytes=digest_bytes)
        result["baseline"] = baseline

        boot_pf = [p for p in (_live_pf(s) for s in early_samples) if p is not None]
        min_pf = min(boot_pf) if boot_pf else None
        max_pf = max(boot_pf) if boot_pf else None
        # Samples at/near floor for digest compare
        near_floor = [s for s in early_samples if _live_pf(s) is not None and _live_pf(s) <= 2]
        result["pressure_telemetry"] = {
            "early_samples": len(early_samples),
            "live_pf_count": len(boot_pf),
            "pages_free_min": min_pf,
            "pages_free_max": max_pf,
            "pages_free_series": boot_pf,
            "near_floor_samples": [
                {
                    "pages_free": s.get("pages_free"),
                    "page_start": s.get("page_start"),
                    "digest": (s.get("bitmap_digest") or {}).get("digest"),
                }
                for s in near_floor[:8]
            ],
        }

        recovery = sample_allocator(sock, symbols, digest_max_bytes=digest_bytes)
        result["recovery_sample"] = recovery

        board = scrape_msg_board(sock, symbols)
        markers = [ln.strip() for ln in (board or "").splitlines() if "ALLOCSOK" in ln]
        result["allocsok_markers"] = markers
        oom_hit = any("OOM HIT" in m for m in markers)
        oom_blk = any("OOM BLOCKED" in m for m in markers)
        scanmiss_cap = any("SCANMISS CAP" in m for m in markers)
        pe_pass = any(m.startswith("ALLOCSOK PASS") for m in markers)
        result["driver_markers"] = {
            "pass": pe_pass,
            "oom_hit": oom_hit,
            "oom_blocked": oom_blk,
            "scanmiss_cap": scanmiss_cap,
            "count": len(markers),
        }

        drain_events(sock, resets, shutdowns)
        status = qmp_exec(sock, {"execute": "query-status"})
        st = status.get("return", {}).get("status")
        if ppm.exists():
            ppm.unlink()
        qmp_exec(sock, {"execute": "screendump", "arguments": {"filename": str(ppm)}})
        time.sleep(0.3)
        w, h, nb = count_non_black_ppm(ppm)
        final = sample_allocator(sock, symbols, digest_max_bytes=digest_bytes)
        result["final"] = final
        result["qemu"].update(
            {
                "status": st,
                "resets": resets[0],
                "shutdowns": shutdowns[0],
                "non_black": nb,
                "ppm": str(ppm).replace("\\", "/"),
            }
        )

        # Classification for this ceiling
        if resets[0] or shutdowns[0] or st not in (None, "running"):
            cls = "UNSAFE"
            result["notes"].append("RESET/shutdown or non-running status")
        elif oom_hit and pe_pass and min_pf is not None and min_pf <= 1:
            cls = "OOM_HIT_FLOOR"
        elif scanmiss_cap and pe_pass:
            cls = "SCANMISS_CAP"
            result["notes"].append(
                "Scan-miss rewind ceiling hit while pages_free still >> 1 — "
                "early-OOM path not reached via AllocPage-only retain"
            )
        elif oom_hit and pe_pass:
            cls = "OOM_HIT_EAX0"
            result["notes"].append(
                "Guest OOM HIT but host did not capture pages_free<=1 — "
                "may be scan-miss rather than early-OOM"
            )
        elif oom_blk and pe_pass:
            cls = "CEILING_BLOCKED"
        elif pe_pass:
            cls = "PASS_NO_OOM_MARKER"
        else:
            cls = "FAIL_OR_NO_MARKERS"

        result["result"] = {
            "passed": pe_pass and resets[0] == 0 and shutdowns[0] == 0,
            "classification": cls,
            "oom_hit": oom_hit,
            "oom_blocked": oom_blk,
            "min_pages_free": min_pf,
            "baseline_pages_free": baseline.get("pages_free"),
            "recovery_pages_free": recovery.get("pages_free"),
            "final_pages_free": final.get("pages_free"),
        }
        artifact.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        log.info(
            "ceiling=%s class=%s min_pf=%s hit=%s → %s",
            max_retain,
            cls,
            min_pf,
            oom_hit,
            artifact,
        )
        return result
    finally:
        if sock is not None:
            try:
                sock.close()
            except OSError:
                pass
        if proc is not None:
            proc.terminate()
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                proc.kill()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--schedule",
        default=",".join(str(x) for x in DEFAULT_SCHEDULE),
        help="comma-separated retain ceilings",
    )
    ap.add_argument("--port", type=int, default=4565)
    ap.add_argument("--wait", type=float, default=180.0)
    ap.add_argument("--sample-interval", type=float, default=0.4)
    ap.add_argument("--digest-bytes", type=int, default=4096)
    ap.add_argument("--disk", action="append", default=[])
    ap.add_argument("--out-dir", default="dev_build/allocsoak")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument(
        "--single",
        type=int,
        default=None,
        help="run only one ceiling (skip schedule progression)",
    )
    ap.add_argument(
        "--repeats",
        type=int,
        default=0,
        help="after first OOM HIT (or final ceiling), repeat N more times",
    )
    args = ap.parse_args(argv)
    setup_logging(args.verbose)

    out_dir = resolve(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.single is not None:
        schedule = [args.single]
    else:
        schedule = [int(x.strip()) for x in args.schedule.split(",") if x.strip()]

    summary: dict[str, Any] = {
        "schema": 1,
        "seed": f"{SEED:#010x}",
        "schedule": schedule,
        "steps": [],
        "decision": None,
        "usable_pages_estimate": None,
    }

    hit_ceiling: int | None = None
    for i, ceiling in enumerate(schedule):
        art = out_dir / f"early-oom-step{i+1}-ret{ceiling}.json"
        try:
            step = run_one_ceiling(
                max_retain=ceiling,
                port=args.port,
                wait_s=args.wait,
                sample_interval=args.sample_interval,
                digest_bytes=args.digest_bytes,
                artifact=art,
                disks=list(args.disk),
            )
        except Exception as ex:  # noqa: BLE001
            log.error("ceiling %s failed: %s", ceiling, ex)
            summary["steps"].append(
                {
                    "max_retain": ceiling,
                    "error": repr(ex),
                    "classification": "TOOLING_ERROR",
                }
            )
            summary["decision"] = "EARLY-OOM STILL INCONCLUSIVE"
            break

        cls = step["result"]["classification"]
        summary["steps"].append(
            {
                "max_retain": ceiling,
                "classification": cls,
                "min_pages_free": step["result"].get("min_pages_free"),
                "oom_hit": step["result"].get("oom_hit"),
                "passed": step["result"].get("passed"),
                "artifact": str(art).replace("\\", "/"),
                "baseline_pages_free": step["result"].get("baseline_pages_free"),
                "qemu_resets": step.get("qemu", {}).get("resets"),
            }
        )
        if summary["usable_pages_estimate"] is None:
            b = step.get("baseline") or {}
            if isinstance(b.get("pages_free"), int):
                summary["usable_pages_estimate"] = {
                    "post_desktop_pages_free": b["pages_free"],
                    "pages_count": b.get("pages_count"),
                    "pagemap_size": b.get("pagemap_size"),
                    "qemu_m_mib": 256,
                }

        if cls == "UNSAFE":
            summary["decision"] = "EARLY-OOM SAFETY BOUNDARY PROVEN"
            summary["boundary_reason"] = (
                f"RESET/shutdown at retain ceiling {ceiling}"
            )
            break
        if cls == "SCANMISS_CAP":
            summary["decision"] = "EARLY-OOM SAFETY BOUNDARY PROVEN"
            summary["boundary_reason"] = (
                "AllocPage-only retain hits scan-miss/page_start wall before "
                f"pages_free<=1 (retain≈{ceiling}, SCANMISS CAP)"
            )
            summary["oom_retain_ceiling"] = ceiling
            hit_ceiling = ceiling  # still repeat for reproducibility
            break
        if cls in ("OOM_HIT_FLOOR", "OOM_HIT_EAX0"):
            hit_ceiling = ceiling
            summary["decision"] = (
                "EARLY-OOM OBSERVABLE"
                if cls == "OOM_HIT_FLOOR"
                else "EARLY-OOM STILL INCONCLUSIVE"
            )
            summary["oom_retain_ceiling"] = ceiling
            if cls == "OOM_HIT_EAX0":
                summary["boundary_reason"] = (
                    "Guest EAX=0 observed but host did not capture pages_free<=1"
                )
            break
        # else escalate

    else:
        # schedule exhausted
        last = summary["steps"][-1] if summary["steps"] else {}
        last_cls = last.get("classification")
        if last_cls == "CEILING_BLOCKED" and (
            isinstance(last.get("min_pages_free"), int) and last["min_pages_free"] > 1
        ):
            summary["decision"] = "EARLY-OOM SAFETY BOUNDARY PROVEN"
            summary["boundary_reason"] = (
                "schedule exhausted: retain ceilings completed without pages_free<=1; "
                f"best min_pf={last.get('min_pages_free')} at max_retain={last.get('max_retain')} "
                "(scan-miss/cursor semantics and/or residual free bits prevent early-OOM)"
            )
        else:
            summary["decision"] = "EARLY-OOM STILL INCONCLUSIVE"
            summary["boundary_reason"] = (
                f"schedule exhausted without clear classification; last={last}"
            )

    # Optional repeats at the hitting (or final) ceiling
    repeat_ceiling = hit_ceiling or (schedule[-1] if schedule else None)
    if (
        args.repeats > 0
        and repeat_ceiling is not None
        and summary.get("decision")
        in (
            "EARLY-OOM OBSERVABLE",
            "EARLY-OOM STILL INCONCLUSIVE",
            "EARLY-OOM SAFETY BOUNDARY PROVEN",
        )
        and "RESET" not in (summary.get("boundary_reason") or "")
    ):
        summary["repeats"] = []
        for r in range(args.repeats):
            art = out_dir / f"early-oom-repeat{r+1}-ret{repeat_ceiling}.json"
            step = run_one_ceiling(
                max_retain=repeat_ceiling,
                port=args.port,
                wait_s=args.wait,
                sample_interval=args.sample_interval,
                digest_bytes=args.digest_bytes,
                artifact=art,
                disks=list(args.disk),
            )
            summary["repeats"].append(
                {
                    "max_retain": repeat_ceiling,
                    "classification": step["result"]["classification"],
                    "min_pages_free": step["result"].get("min_pages_free"),
                    "oom_hit": step["result"].get("oom_hit"),
                    "passed": step["result"].get("passed"),
                    "artifact": str(art).replace("\\", "/"),
                    "qemu_resets": step.get("qemu", {}).get("resets"),
                }
            )
            if step["result"]["classification"] == "UNSAFE":
                summary["decision"] = "EARLY-OOM SAFETY BOUNDARY PROVEN"
                summary["boundary_reason"] = f"RESET during repeat {r+1}"
                break
            if (
                summary["decision"] == "EARLY-OOM OBSERVABLE"
                and step["result"]["classification"] != "OOM_HIT_FLOOR"
            ):
                summary["decision"] = "EARLY-OOM STILL INCONCLUSIVE"
                summary["notes"] = summary.get("notes", []) + [
                    f"repeat {r+1} did not reconfirm pages_free<=1"
                ]

    # Promote EAX0 + min_pf<=1 across any step/repeat
    def _any_floor(entries: list[dict[str, Any]]) -> bool:
        return any(
            e.get("oom_hit") and isinstance(e.get("min_pages_free"), int) and e["min_pages_free"] <= 1
            for e in entries
        )

    all_entries = list(summary["steps"]) + list(summary.get("repeats") or [])
    if _any_floor(all_entries) and summary.get("decision") != "EARLY-OOM SAFETY BOUNDARY PROVEN":
        # Confirm no unsafe
        if not any(e.get("classification") == "UNSAFE" for e in all_entries):
            summary["decision"] = "EARLY-OOM OBSERVABLE"

    out = out_dir / "early-oom-summary.json"
    out.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"decision": summary["decision"], "summary": str(out)}, indent=2))
    log.info("SUMMARY %s → %s", summary["decision"], out)
    return EXIT_PASS


if __name__ == "__main__":
    raise SystemExit(main())
