"""Bounded Stage-4 early-OOM observation experiment (host tooling only).

Progressively raises the disposable PE driver's retain ceiling and runs QEMU
soaks until either:

  * ``ALLOCSOK OOM HIT`` (AllocPage returned 0), or
  * a safety/stability boundary is proven, or
  * the schedule is exhausted without OOM.

Does **not** modify production allocator code or add Rust gates.
"""

